std::vector<Pixel> Application::LoadPalette()
{
	size_t paletteSize = paletteData.size() / 3;
	std::vector<Pixel> result;
	result.reserve(paletteSize);
	for (int i = 0; i < paletteSize; i++) {
		result.push_back(Pixel{
			.r = paletteData[i * 3 + 0],
			.g = paletteData[i * 3 + 1],
			.b = paletteData[i * 3 + 2],
			.a = 255,
		});
	}
	return result;
}